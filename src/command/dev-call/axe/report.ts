// Ranks are ascending (0 = worst), so severity and standard both default to
// ascending; reach columns default to biggest-first.
const kTableScript = `
  var AI = JSON.parse(document.getElementById('axe-ai').textContent);
  function copyText(text, el){
    navigator.clipboard.writeText(text).then(function(){
      if (!el) return; var was = el.textContent; el.textContent = 'copied \\u2713';
      setTimeout(function(){ el.textContent = was; }, 1200);
    });
  }
  var tbody = document.querySelector('#findings tbody');
  function pairs(){ var out=[], cur=null; Array.prototype.forEach.call(tbody.children, function(tr){
    if (tr.classList.contains('f')) { cur = {f:tr, d:null}; out.push(cur); } else if (cur) { cur.d = tr; } }); return out; }
  function onRowClick(e){
    var cp = e.target.closest('[data-copy]'); if (cp) { copyText(AI.briefings[cp.dataset.copy], cp); return; }
    var ci = e.target.closest('[data-copyid]'); if (ci) { copyText(ci.dataset.copyid, ci); return; }
    if (e.target.closest('a')) return;
    var row = e.target.closest('tr.f'); if (!row) return;
    var d = row.nextElementSibling;
    if (d && d.classList.contains('d')) { d.hidden = !d.hidden; row.classList.toggle('open'); }
  }
  Array.prototype.forEach.call(document.querySelectorAll('table.findings tbody'), function(tb){ tb.addEventListener('click', onRowClick); });
  var DEFAULT_DIR = { standard:1, class:1, rule:1, severity:1, pages:-1, instances:-1 };
  var sortKey = null, dir = 1;
  Array.prototype.forEach.call(document.querySelectorAll('#findings th[data-key]'), function(th){
    th.addEventListener('click', function(){
      var key = th.dataset.key, type = th.dataset.type || 'str';
      dir = (sortKey === key) ? -dir : DEFAULT_DIR[key]; sortKey = key;
      var ps = pairs();
      ps.sort(function(a,b){
        var va = a.f.dataset[key], vb = b.f.dataset[key];
        if (type === 'num') return (parseFloat(va) - parseFloat(vb)) * dir;
        return va.localeCompare(vb) * dir;
      });
      ps.forEach(function(p){ tbody.appendChild(p.f); if (p.d) tbody.appendChild(p.d); });
      Array.prototype.forEach.call(document.querySelectorAll('#findings th'), function(h){ h.removeAttribute('aria-sort'); });
      th.setAttribute('aria-sort', dir > 0 ? 'ascending' : 'descending');
    });
  });
`;

function occurrenceRows(finding: AxeFinding): string {
  return finding.occurrences.map((occurrence) =>
    `<tr><td>${esc(occurrence.page)}</td>` +
    `<td class="cells">${occurrence.cells.map(esc).join("<br>")}</td>` +
    `<td><code>${esc(occurrence.target)}</code></td>` +
    `<td><code class="snip">${esc(occurrence.html)}</code></td>` +
    `<td>${esc(occurrence.detail)}</td></tr>`
  ).join("");
}

function findingRows(findings: AxeFinding[], showWhy: boolean): string {
  return findings.map((finding) => {
    const why = showWhy
      ? `\n  <td class="why">${esc(finding.baselineNote ?? "")}</td>`
      : "";
    const columns = showWhy ? 9 : 8;
    return `<tr class="f" data-standard="${finding.standardRank}" ` +
      `data-severity="${finding.severityRank}" ` +
      `data-rule="${esc(finding.rule)}" ` +
      `data-class="${finding.label === "systemic" ? 0 : 1}" ` +
      `data-pages="${finding.pages.length}" ` +
      `data-instances="${finding.instances}">
  <td class="std" title="${esc(finding.conformance)}">${
        esc(finding.standard)
      }</td>
  <td><span class="badge impact-${finding.impact}">${
        esc(finding.impact)
      }</span></td>
  <td><code class="rule">${esc(finding.rule)}</code></td>
  <td><span class="badge ${finding.label}">${finding.label}</span></td>
  <td class="num">${finding.pages.length}</td>
  <td class="num">${finding.instances}</td>
  <td class="dcell">${esc(finding.detail || finding.examples[0])}</td>${why}
  <td class="act"><button class="cp" data-copy="${
        esc(finding.id)
      }" title="Copy an AI briefing (markdown) for this finding">copy</button><code class="idchip" data-copyid="${
        esc(finding.id)
      }" title="Copy this finding's id">${esc(finding.id)}</code></td></tr>
<tr class="d" hidden><td colspan="${columns}">
  <table class="occ"><thead><tr><th>page</th><th>cells (width·theme)</th><th>selector</th><th>element</th><th>detail</th></tr></thead>
  <tbody>${occurrenceRows(finding)}</tbody></table></td></tr>`;
  }).join("\n");
}

function tableHead(showWhy: boolean): string {
  return `<thead><tr>
  <th data-key="standard" data-type="num">standard</th>
  <th data-key="severity" data-type="num">severity</th>
  <th data-key="rule" data-type="str">rule</th>
  <th data-key="class" data-type="num">class</th>
  <th class="num" data-key="pages" data-type="num">pages</th>
  <th class="num" data-key="instances" data-type="num">occurrences</th>
  <th>detail</th>${showWhy ? "\n  <th>why accepted</th>" : ""}
  <th title="Copy an AI briefing (markdown), or the finding id">AI</th>
</tr></thead>`;
}

/** Render `findings.json` as a self-contained HTML report. */
export function renderReport(results: AxeFindings): string {
  const newFindings = results.findings.filter((finding) => !finding.baselined);
  const baselined = results.findings.filter((finding) => finding.baselined);

  // JSON in a <script type="application/json">; escape `<` so the payload can't
  // terminate the block early.
  const aiData = JSON.stringify({
    briefings: Object.fromEntries(
      results.findings.map((finding) => [finding.id, briefing(finding)]),
    ),
  }).replace(/</g, "\\u003c");

  const notOk = results.notOkCells.length
    ? `<p class="warn"><strong>Non-OK cells (fail-closed — not counted as passing):</strong> ${
      results.notOkCells.map((cell) =>
        `${esc(cell.status)} ${esc(cell.page)} ${esc(cell.viewport)}·${
          esc(cell.theme)
        }`
      ).join("; ")
    }</p>`
    : "";

  const stale = results.baseline.stale;
  const staleNotice = stale.length
    ? `<p class="mut stale">↳ ${stale.length} baseline entr${
      stale.length === 1 ? "y" : "ies"
    } not seen in this scan — if this was a full-page scan they are resolved and can be pruned from <code>${
      esc(results.baseline.file)
    }</code>: ${
      stale.map((entry) => `<code>${esc(entry.id ?? entry.signature)}</code>`)
        .join(", ")
    }</p>`
    : "";

  const baselinedSection = baselined.length
    ? `<details class="baselined"><summary>Known / baselined — ${baselined.length} finding${
      plural(baselined.length)
    } accepted, suppressed from the list above</summary>
<table class="findings" id="baselined">${tableHead(true)}<tbody>
${findingRows(baselined, true)}
</tbody></table></details>`
    : "";

  return `<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>axe site audit — ${esc(results.pagesScanned)} pages</title>
<style>${kStyles}</style></head><body>
<h1>axe site audit</h1>
<p class="sub">${esc(results.pagesScanned)} pages · ${esc(results.cells.ok)}/${
    esc(results.cells.total)
  } cells ok · axe-core ${esc(results.axeVersion ?? "unknown")} · generated ${
    esc(results.generated)
  }<br>
<strong>${newFindings.length} new finding${
    plural(newFindings.length)
  }</strong> shown below${
    baselined.length
      ? ` · ${baselined.length} baselined (known, collapsed)`
      : ""
  }.<br>
Sorted by standard, then severity — click any header to re-sort; click a row to see occurrences.
<strong>systemic</strong> = repeats from a shared source (fix once, fixes many) · <strong>localized</strong> = one-off. <strong>pages</strong> = distinct pages affected; <strong>occurrences</strong> = distinct elements.</p>
${notOk}
${staleNotice}
<table class="findings" id="findings">${tableHead(false)}<tbody>
${findingRows(newFindings, false)}
</tbody></table>
${baselinedSection}
<script id="axe-ai" type="application/json">${aiData}</script>
<script>${kTableScript}</script>
</body></html>
`;
}
