import { AxeFinding, AxeFindings } from "./schemas.ts";

function esc(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function plural(count: number, singular = "", many = "s"): string {
  return count === 1 ? singular : many;
}

// How many occurrences an AI briefing lists before it starts summarizing.
const kOccurrenceCap = 15;

const kBriefingPreamble =
  "This is from an axe-core accessibility audit of a website generated by " +
  "**Quarto**. Fixes usually belong in the Quarto *source* — a `.qmd`, " +
  "`_quarto.yml`, `brand.yml`, or a theme `.scss` — not in the generated " +
  "site HTML (it is overwritten every render). Some findings come from " +
  "Quarto's shared templates (navbar, footer, listings); those may warrant an " +
  "upstream Quarto issue rather than a local change.";

/** A markdown briefing for one finding, sized to paste into a chat. */
export function briefing(finding: AxeFinding): string {
  const shown = finding.occurrences.slice(0, kOccurrenceCap).map((occurrence) =>
    `- \`${occurrence.page}\` [${occurrence.cells.join(", ")}] — selector ` +
    `\`${occurrence.target}\`\n  \`\`\`html\n  ${occurrence.html}\n  \`\`\``
  ).join("\n");
  const hidden = finding.occurrences.length - kOccurrenceCap;
  const more = hidden > 0 ? `\n- …and ${hidden} more` : "";
  const fixNote = finding.label === "systemic"
    ? " Fixing the shared source fixes all of them."
    : "";
  return [
    `# Accessibility issue: ${finding.rule} — ${finding.standard} ` +
    `(${finding.impact})`,
    ``,
    kBriefingPreamble,
    ``,
    `- **Rule:** \`${finding.rule}\`${
      finding.help ? ` — ${finding.help}` : ""
    }`,
    `- **Standard:** ${finding.conformance || "—"}`,
    `- **Severity:** ${finding.impact}`,
    `- **Scope:** ${finding.label} — ${finding.pages.length} page${
      plural(finding.pages.length)
    }, ${finding.instances} occurrence${plural(finding.instances)}.${fixNote}`,
    `- **Problem:** ${finding.detail || finding.occurrences[0]?.detail || ""}`,
    ...(finding.helpUrl ? [`- **Reference:** ${finding.helpUrl}`] : []),
    `- **Finding id:** \`${finding.id}\` (look up the full record in ` +
    `\`findings.json\`)`,
    ``,
    `## Affected elements (${finding.occurrences.length}${
      hidden > 0 ? `, showing ${kOccurrenceCap}` : ""
    })`,
    shown + more,
    ``,
    `Please help me fix this in the Quarto source.`,
  ].join("\n");
}

