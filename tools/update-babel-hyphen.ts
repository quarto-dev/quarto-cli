export interface BabelHyphenTables {
  hyphen_synonyms: Record<string, string>;
  babel_hyphen_map: Record<string, string>;
  babel_hyphen_codes: Record<string, string>;
}

const kTableNames = [
  "hyphen_synonyms",
  "babel_hyphen_map",
  "babel_hyphen_codes",
] as const;

function validateTables(tables: unknown): BabelHyphenTables {
  if (typeof tables !== "object" || tables === null || Array.isArray(tables)) {
    throw new Error("Invalid babel-hyphen.json: expected an object");
  }

  const input = tables as Record<string, unknown>;
  for (const name of kTableNames) {
    const table = input[name];
    if (
      typeof table !== "object" || table === null || Array.isArray(table)
    ) {
      throw new Error(`Invalid ${name}: expected an object of string values`);
    }
    for (const [key, value] of Object.entries(table)) {
      if (typeof value !== "string") {
        throw new Error(`Invalid ${name}.${key}: expected a string value`);
      }
    }
  }
  return tables as BabelHyphenTables;
}

function renderTable(
  exportName: string,
  comment: string,
  table: Record<string, string>,
): string {
  const keys = Object.keys(table).sort((a, b) => a < b ? -1 : a > b ? 1 : 0);
  const entries = keys.map((key) =>
    `  ${JSON.stringify(key)}: ${JSON.stringify(table[key])},\n`
  ).join("");
  return `// ${comment}\nexport const ${exportName}: Record<string, string> = {\n${entries}};\n`;
}

export function renderBabelHyphenModule(tables: unknown): string {
  const validated = validateTables(tables);
  return `/*
 * babel-hyphen.ts
 *
 * Copyright (C) 2026 Posit Software, PBC
 *
 * Generated by tools/update-babel-hyphen.ts from babel-hyphen.json in the
 * daily regex.tar.gz of rstudio/tinytex-releases. Do not edit by hand:
 * see dev-docs/tinytex-pattern-maintenance.md.
 */

${renderTable(
    "kHyphenSynonyms",
    "language.dat synonyms to canonical names (hyphen_synonyms)",
    validated.hyphen_synonyms,
  )}
${renderTable(
    "kBabelHyphenMap",
    "babel locale names to language.dat names (babel_hyphen_map)",
    validated.babel_hyphen_map,
  )}
${renderTable(
    "kBabelHyphenCodes",
    "Codes from babel-<code>.ini filenames to hyphenrules values (babel_hyphen_codes)",
    validated.babel_hyphen_codes,
  )}`;
}

if (import.meta.main) {
  const [input, output] = Deno.args;
  if (!input) {
    console.error(
      "Usage: deno run --no-config --no-lock --allow-read --allow-write tools/update-babel-hyphen.ts <babel-hyphen.json> [<output.ts>]",
    );
    Deno.exit(1);
  }

  const tables = JSON.parse(Deno.readTextFileSync(input));
  const outputPath = output ?? new URL(
    "../src/command/render/latexmk/babel-hyphen.ts",
    import.meta.url,
  );
  Deno.writeTextFileSync(outputPath, renderBabelHyphenModule(tables));
}
